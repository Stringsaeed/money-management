import { spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const MIN_MIGRATION_VERSION = 16;
export const TRACKING_TABLE = "trove_schema_migrations";
export const MIGRATION_TAG_PATTERN = /^\d{4}_[a-z0-9][a-z0-9_-]*$/;

const JOURNAL_PATH = fileURLToPath(
  new URL("../src/migrations/meta/_journal.json", import.meta.url),
);
const MIGRATIONS_DIR = fileURLToPath(new URL("../src/migrations/", import.meta.url));
const REQUIRED_ENV = [
  "PLANETSCALE_SERVICE_TOKEN_ID",
  "PLANETSCALE_SERVICE_TOKEN",
  "PLANETSCALE_ORG",
  "PLANETSCALE_DATABASE",
  "PLANETSCALE_BRANCH",
];

/**
 * @param {string} source
 * @returns {string}
 */
export function sha256(source) {
  return createHash("sha256").update(source, "utf8").digest("hex");
}

/**
 * Drizzle writes this marker between SQL statements. Each statement is then
 * executed inside the single transaction generated by buildMigrationQuery.
 *
 * @param {string} source
 * @returns {string[]}
 */
export function splitMigrationStatements(source) {
  return source
    .split("--> statement-breakpoint")
    .map((statement) => statement.trim())
    .filter(Boolean);
}

/**
 * @param {string} source
 * @param {string} tag
 */
function assertTransactionalSource(source, tag) {
  const statements = splitMigrationStatements(source);
  if (statements.length === 0) throw new Error(`Migration ${tag} is empty.`);

  for (const statement of statements) {
    const normalized = statement
      .replace(/^(?:\s|--[^\n]*(?:\n|$)|\/\*[\s\S]*?\*\/)+/, "")
      .toUpperCase();
    if (/^(BEGIN|START TRANSACTION|COMMIT|ROLLBACK)\b/.test(normalized)) {
      throw new Error(`Migration ${tag} must not manage its own transaction.`);
    }
    if (/^(CREATE|DROP)\s+INDEX\s+CONCURRENTLY\b/.test(normalized)) {
      throw new Error(`Migration ${tag} uses non-transactional index concurrency.`);
    }
  }
}

/**
 * @param {string} source
 * @returns {boolean}
 */
export function containsDestructiveSql(source) {
  return /\b(?:DELETE|DROP|TRUNCATE)\b/i.test(source);
}

/**
 * Read the Drizzle journal and expose only future, exact tags. Existing
 * 0007–0015 entries are intentionally ignored and can never be replayed by
 * this production runner.
 *
 * @param {{ journalPath?: string, migrationsDir?: string }} [options]
 */
export function loadJournalMigrations({
  journalPath = JOURNAL_PATH,
  migrationsDir = MIGRATIONS_DIR,
} = {}) {
  let journal;
  try {
    journal = JSON.parse(readFileSync(journalPath, "utf8"));
  } catch (error) {
    throw new Error(`Unable to read Postgres migration journal: ${error.message}`);
  }
  if (!journal || !Array.isArray(journal.entries)) {
    throw new Error("Postgres migration journal must contain entries[].");
  }

  const root = resolve(migrationsDir);
  const seenTags = new Set();
  let previousVersion = 0;
  const migrations = [];

  for (const entry of journal.entries) {
    const tag = entry?.tag;
    if (typeof tag !== "string" || !MIGRATION_TAG_PATTERN.test(tag)) {
      throw new Error(`Invalid Postgres migration tag in journal: ${String(tag)}.`);
    }
    const version = Number(tag.slice(0, 4));
    if (!Number.isInteger(version) || version <= previousVersion) {
      throw new Error(`Postgres migration journal tags must be strictly increasing: ${tag}.`);
    }
    previousVersion = version;
    if (seenTags.has(tag)) throw new Error(`Duplicate Postgres migration tag: ${tag}.`);
    seenTags.add(tag);
    if (version < MIN_MIGRATION_VERSION) continue;

    const fileName = `${tag}.sql`;
    if (basename(fileName) !== fileName)
      throw new Error(`Invalid migration filename: ${fileName}.`);
    const filePath = resolve(root, fileName);
    if (!filePath.startsWith(`${root}/`)) {
      throw new Error(`Migration ${tag} resolves outside the migrations directory.`);
    }
    const source = readFileSync(filePath, "utf8");
    assertTransactionalSource(source, tag);
    migrations.push({
      version,
      tag,
      fileName,
      sha256: sha256(source),
      statements: splitMigrationStatements(source),
      destructive: containsDestructiveSql(source),
    });
  }

  return migrations;
}

/**
 * @param {Array<{ version: number, tag: string, fileName: string, sha256: string, statements: string[], destructive: boolean }>} migrations
 * @param {string} tag
 */
export function selectMigration(migrations, tag) {
  if (typeof tag !== "string" || !MIGRATION_TAG_PATTERN.test(tag)) {
    throw new Error("PLANETSCALE_MIGRATION_TAG must be an exact journal tag, not SQL input.");
  }
  const migration = migrations.find((candidate) => candidate.tag === tag);
  if (!migration) {
    const allowed = migrations.map((candidate) => candidate.tag).join(", ");
    throw new Error(
      `Migration ${tag} is not allowlisted in the journal. Allowed: ${allowed || "none"}.`,
    );
  }
  return migration;
}

/**
 * @param {string} value
 * @returns {string}
 */
function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

/**
 * @param {string} value
 * @returns {string}
 */
function dollarQuoted(value) {
  let tag = `trove_migration_${sha256(value).slice(0, 16)}`;
  while (value.includes(`$${tag}$`)) tag += "_x";
  return `$${tag}$${value}$${tag}$`;
}

/**
 * Build one transaction. The advisory lock serializes migration attempts and
 * the marker row makes retries no-op or fail closed on checksum drift.
 *
 * @param {{ version: number, tag: string, sha256: string, statements: string[] }} migration
 */
export function buildMigrationQuery(migration) {
  const table = `"${TRACKING_TABLE}"`;
  const statements = migration.statements
    .map((statement) => `    EXECUTE ${dollarQuoted(statement)};`)
    .join("\n");

  return [
    "BEGIN;",
    `CREATE TABLE IF NOT EXISTS ${table} (`,
    '  "version" integer PRIMARY KEY,',
    '  "tag" text NOT NULL UNIQUE,',
    '  "sha256" text NOT NULL,',
    '  "applied_at" timestamp with time zone NOT NULL DEFAULT now()',
    ");",
    `SELECT pg_advisory_xact_lock(hashtext(${sqlString(TRACKING_TABLE)}));`,
    "DO $trove_schema_migration_runner$",
    "DECLARE",
    `  latest_version integer DEFAULT ${MIN_MIGRATION_VERSION - 1};`,
    "  existing_tag text;",
    "  existing_sha256 text;",
    "BEGIN",
    `  SELECT COALESCE(MAX("version"), ${MIN_MIGRATION_VERSION - 1}) INTO latest_version FROM ${table};`,
    `  SELECT "tag", "sha256" INTO existing_tag, existing_sha256 FROM ${table} WHERE "version" = ${migration.version};`,
    "  IF NOT FOUND THEN",
    `    IF ${migration.version} <> latest_version + 1 THEN`,
    `      RAISE EXCEPTION 'Migration ${migration.tag} must follow version %.', latest_version;`,
    "    END IF;",
    statements,
    `    INSERT INTO ${table} ("version", "tag", "sha256") VALUES (${migration.version}, ${sqlString(migration.tag)}, ${sqlString(migration.sha256)});`,
    `  ELSIF existing_tag IS DISTINCT FROM ${sqlString(migration.tag)} OR existing_sha256 IS DISTINCT FROM ${sqlString(migration.sha256)} THEN`,
    `    RAISE EXCEPTION 'Migration ${migration.tag} is already recorded with a different tag or checksum.';`,
    "  END IF;",
    "END;",
    "$trove_schema_migration_runner$;",
    "COMMIT;",
  ].join("\n");
}

/**
 * @param {{ organization: string, database: string, branch: string, migration: { destructive: boolean, version: number, tag: string, sha256: string, statements: string[] }, dbname?: string }} input
 */
export function buildPscaleArgs({
  organization,
  database,
  branch,
  migration,
  dbname = "postgres",
}) {
  const args = [
    "sql",
    database,
    branch,
    "--org",
    organization,
    "--format",
    "json",
    "--role",
    "admin",
    "--dbname",
    dbname,
  ];
  if (migration.destructive) args.push("--force");
  args.push("--query", buildMigrationQuery(migration));
  return args;
}

/**
 * @param {string[]} args
 * @param {NodeJS.ProcessEnv} environment
 * @returns {Promise<Record<string, unknown>>}
 */
export function executePscale(args, environment) {
  return new Promise((resolve, reject) => {
    const child = spawn("pscale", args, {
      env: { ...environment },
      stdio: ["ignore", "pipe", "ignore"],
    });
    let stdout = "";
    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.once("error", reject);
    child.once("close", (code) => {
      let payload;
      try {
        payload = JSON.parse(stdout.trim());
      } catch {
        reject(new Error(`pscale returned invalid JSON (exit ${code ?? "unknown"}).`));
        return;
      }
      if (code !== 0 || payload.status !== "ok") {
        const detail = typeof payload.error === "string" ? ` ${payload.error}` : "";
        reject(new Error(`pscale migration command failed.${detail}`));
        return;
      }
      resolve(payload);
    });
  });
}

/**
 * @param {NodeJS.ProcessEnv} environment
 */
function targetFromEnv(environment) {
  for (const name of REQUIRED_ENV) {
    if (!environment[name]?.trim()) {
      throw new Error(`Missing required migration environment value: ${name}.`);
    }
  }
  return {
    organization: environment.PLANETSCALE_ORG.trim(),
    database: environment.PLANETSCALE_DATABASE.trim(),
    branch: environment.PLANETSCALE_BRANCH.trim(),
    dbname: environment.PLANETSCALE_DBNAME?.trim() || "postgres",
  };
}

/**
 * @param {{ environment?: NodeJS.ProcessEnv, execute?: typeof executePscale, journalPath?: string, migrationsDir?: string }} [options]
 */
export async function runPostgresMigration({
  environment = process.env,
  execute = executePscale,
  journalPath,
  migrationsDir,
} = {}) {
  const target = targetFromEnv(environment);
  const migrations = loadJournalMigrations({ journalPath, migrationsDir });
  const migration = selectMigration(migrations, environment.PLANETSCALE_MIGRATION_TAG);
  const payload = await execute(buildPscaleArgs({ ...target, migration }), environment);
  if (!payload || payload.status !== "ok") {
    throw new Error("pscale migration command did not report success.");
  }

  return {
    ok: true,
    migration: { version: migration.version, tag: migration.tag, sha256: migration.sha256 },
    target: { organization: target.organization, database: target.database, branch: target.branch },
    pscale: { status: payload.status, rows_affected: payload.rows_affected ?? 0 },
  };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    console.log(JSON.stringify(await runPostgresMigration(), null, 2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : "Postgres migration failed.");
    process.exitCode = 1;
  }
}
